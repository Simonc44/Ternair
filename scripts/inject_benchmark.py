"""Inject the WikiText-2 benchmark results into README.md.

Reads benchmark_results.json, formats a Markdown table,
and replaces the section between:
  <!-- BENCHMARK_RESULTS --> ... <!-- END_BENCHMARK_RESULTS -->
in README.md.  If the markers are absent, appends the table at the end.

Called by .github/workflows/benchmark.yml after the benchmark script runs.
"""

from __future__ import annotations

import datetime
import json
import pathlib
import re


def load_results(path: str = "benchmark_results.json") -> dict:
    with open(path, encoding="utf-8") as f:
        return json.load(f)


def build_table(results: dict) -> str:
    cfg    = results["config"]
    models = results["models"]

    t  = models.get("Ternair (ternary)", models.get("ternair", {}))
    fp = models.get("FP16 baseline",     models.get("fp16",    {}))

    ppl_t   = t.get("perplexity",     float("nan"))
    ppl_fp  = fp.get("perplexity",    float("nan"))
    size_t  = t.get("size_mib",       0.0)
    size_fp = fp.get("size_mib",      0.0)
    spd_t   = t.get("tokens_per_sec", 0.0)
    spd_fp  = fp.get("tokens_per_sec", 0.0)
    params  = t.get("params",         0)

    ppl_delta   = ppl_t - ppl_fp
    ppl_pct     = ppl_delta / max(ppl_fp, 0.001) * 100
    size_ratio  = size_fp  / max(size_t,  0.001)
    speed_ratio = spd_t    / max(spd_fp,  0.001)

    run_date = cfg.get("date", datetime.datetime.utcnow().isoformat(timespec="seconds"))
    steps    = cfg.get("steps",   "?")
    device   = cfg.get("device",  "cpu")
    profile  = cfg.get("profile", "tiny")
    storage  = cfg.get("storage", "fastpacked")

    lines = [
        "<!-- BENCHMARK_RESULTS -->",
        "## Benchmark WikiText-2 \u2014 Ternair vs FP16",
        "",
        f"> Profile `{profile}` \u00b7 storage `{storage}` "
        f"\u00b7 {steps} training steps \u00b7 device `{device}`  ",
        f"> {params:,} parameters \u00b7 Last run: {run_date} (auto-generated by CI)",
        "",
        "| Model | PPL \u2193 | Size (MiB) \u2193 | Tokens/sec \u2191 |",
        "|-------|------:|-------------:|-------------:|",
        f"| **Ternair (ternary)** | **{ppl_t:.2f}** "
        f"| **{size_t:.1f}** | **{spd_t:.1f}** |",
        f"| FP16 baseline | {ppl_fp:.2f} | {size_fp:.1f} | {spd_fp:.1f} |",
        "",
        "**Summary:**",
        f"- PPL overhead vs FP16: {ppl_delta:+.2f} ({ppl_pct:+.1f}%)",
        f"- Size compression: **{size_ratio:.1f}\u00d7**",
        f"- Speed ratio: {speed_ratio:.2f}\u00d7",
        "<!-- END_BENCHMARK_RESULTS -->",
    ]
    return "\n".join(lines)


def patch_readme(table: str, readme_path: str = "README.md") -> None:
    readme = pathlib.Path(readme_path).read_text(encoding="utf-8")
    pattern = r"<!-- BENCHMARK_RESULTS -->.*?<!-- END_BENCHMARK_RESULTS -->"
    if re.search(pattern, readme, flags=re.DOTALL):
        readme = re.sub(pattern, table, readme, flags=re.DOTALL)
    else:
        readme = readme + "\n\n" + table
    pathlib.Path(readme_path).write_text(readme, encoding="utf-8")
    print(f"README.md patched ({readme_path}).")


if __name__ == "__main__":
    results = load_results()
    table   = build_table(results)
    patch_readme(table)
